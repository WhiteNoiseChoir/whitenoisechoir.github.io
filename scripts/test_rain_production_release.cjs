#!/usr/bin/env node
"use strict";
const resolve=require("./resolve_review_media.cjs");
const fs=require("node:fs"),crypto=require("node:crypto"),assert=require("node:assert/strict");
const read=p=>fs.readFileSync(p,"utf8"),json=p=>JSON.parse(read(p));
const catalog=json("catalog/library.json"),plans=json("catalog/planned-sounds.json").planned,families=json("catalog/family-registry.json").families,provenance=json("audio/rain-first-wave-provenance.json");
const hls=json("audio/continuous/manifest.json"),old=json("audio/original-22-hls-lock.json");
const sha=p=>crypto.createHash("sha256").update(fs.readFileSync(p)).digest("hex");
const added=["light-rain-real","rain-tin-roof-real","distant-thunder-real"];
assert.equal(catalog.sounds.length,35);
assert.equal(plans.length,70);
assert.equal(plans.filter(x=>x.playable).length,13);
assert.equal(plans.filter(x=>!x.playable).length,57);
assert.equal(families.length,13);
assert.deepEqual(families.find(x=>x.id==="rain").existing_ids.slice(2,5),added);
assert.equal(hls.records.length,35);
assert.equal(hls.applies_to.length,35);
assert.equal(old.records.length,22);
assert.equal(provenance.status,"OWNER_APPROVED_FOR_AUDIO");
assert.equal(provenance.tracks.length,3);
for(const r of old.records){
 const now=hls.records.find(x=>x.id===r.id);
 assert.ok(now,"original audio still in HLS manifest "+r.id);
 assert.equal(now.master_sha256,r.master_sha256,"old MP3 checksum changed "+r.id);
 assert.equal(now.playlist_sha256,r.playlist_sha256,"old HLS checksum changed "+r.id);
 assert.equal(now.segment_count_per_source_cycle,r.segment_count_per_source_cycle);
 assert.equal(sha(now.playlist_file),r.playlist_sha256);
}
for(const entry of provenance.tracks){
 const s=catalog.sounds.find(x=>x.id===entry.production_id);
 assert.ok(s,"catalog missing "+entry.production_id);
 assert.equal(s.status,"listening-approved");
 assert.equal(s.cat,"rain");
 const mp3=entry.production_mp3;
 assert.equal(sha(mp3),entry.master_sha256,"promoted MP3 MUST equal owner-audition MP3");
 assert.equal(sha(resolve(entry.review_mp3)),entry.master_sha256,"approved review asset changed");
 assert.equal(entry.master_seconds,600);
 assert.equal(entry.license,"CC0-1.0");
 assert.equal(entry.owner_listening_status,"APPROVED_BY_OWNER_2026-11-08");
 assert.equal(entry.original_wav_downloaded,false);
 const rec=hls.records.find(x=>x.id===s.id);
 assert.ok(rec,"HLS missing "+s.id);
 assert.equal(rec.master_sha256,entry.master_sha256);
 assert.equal(rec.source_license,"CC0-1.0");
 assert.equal(rec.source_page,entry.source_page);
 assert.equal(sha(rec.playlist_file),rec.playlist_sha256);
 assert.ok(rec.repeated_cycles>=1008);
 assert.ok(rec.native_stream_duration_hours>=167.9);
 assert.ok(rec.segment_count_per_source_cycle>=9);
 assert.ok(fs.existsSync("audio/continuous/"+s.id+"/part_000.ts"));
 const playlist=read(rec.playlist_file);
 assert.ok(playlist.startsWith("#EXTM3U"));
 assert.ok(playlist.includes("#EXT-X-DISCONTINUITY"));
 assert.ok(playlist.includes("#EXT-X-ENDLIST"));
 const page=read("sounds/"+s.slug+"/index.html");
 assert.ok(page.includes('name="robots" content="noindex,follow"'),"audio approval is NOT SEO indexing approval "+s.id);
 assert.ok(page.includes('data-sound="'+s.id+'"'));
 assert.ok(page.includes('data-mp3="/audio/'+s.id+'.mp3'));
 assert.ok(page.includes('/audio/continuous/'+s.id+'/continuous.m3u8'));
 assert.ok(page.includes('<audio controls loop preload="none"'));
 assert.ok(page.includes('rel="canonical" href="https://whitenoisechoir.com/sounds/'+s.slug+'/'));
 assert.ok(page.includes('"@type":"AudioObject"'));
 assert.ok(page.includes(entry.source_page));
 assert.equal(read("sitemap.xml").includes("/sounds/"+s.slug+"/"),false);
 const planned=plans.find(x=>x.plan_id===entry.plan_id);
 assert.equal(planned.production_id,s.id);
 assert.equal(planned.owner_listening_approval,"APPROVED_BY_OWNER_2026-11-08");
 assert.equal(planned.qa.master_sha256,entry.master_sha256);
 assert.equal(planned.seo_status,"noindex,follow");
}
assert.equal((read("sitemap.xml").match(/<loc>/g)||[]).length,18);
for(const slug of ["light-rain","rain-on-tin-roof","distant-thunder"])assert.ok(read("sounds/rain/index.html").includes('href="/sounds/'+slug+'/"'));
assert.equal((read("sounds/index.html").match(/data-wnc-existing-id="/g)||[]).length,35);
assert.ok(read("index.html").includes("13 families · 35 catalog sources"));
assert.equal(JSON.parse(read("index.html").split("var recipes=")[1].split("];")[0]+"]").length,45);
for(const r of added)assert.ok(read("index.html").includes('["'+r+'",'),"homepage row missing "+r);
assert.ok(read("sources.html").includes("The nine recordings"));
assert.ok(!read("audio/rain-first-wave-provenance.json").includes("lossless_WAV_source"));
console.log("RAIN_PRODUCTION_QA_PASS "+JSON.stringify({newSounds:added.length,existingProtected:22,hls:35,soundPages:35,indexableSoundPages:10,sitemap:18,presets:45,unreleasedPlanned:57,approval:"OWNER_2026_11_08"}));
