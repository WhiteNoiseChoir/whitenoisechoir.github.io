#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),assert=require("node:assert/strict"),cp=require("node:child_process"),crypto=require("node:crypto");
const read=x=>fs.readFileSync(x,"utf8"),data=x=>JSON.parse(read(x));
const blob=p=>{const b=fs.readFileSync(p);return crypto.createHash("sha1").update(Buffer.from("blob "+b.length+"\0")).update(b).digest("hex")};
assert.equal(blob("sounds/ocean-waves/index.html"),"1ffb0a6e4e8368f3c37418cbfe2bbca4f6312573");
assert.equal(blob("audits/sitemap-before-studio.xml"),"1fb26b9e9186b3f9dba89234cc60c7bc3bb2228d");
assert.equal(blob("assets/persistent-router.js"),"ba81a3a6d230b7e26a8fb9c770ea681570b41027");
const ocean=read("sounds/ocean-waves/index.html");
assert.ok(ocean.includes('href="https://whitenoisechoir.com/sounds/ocean-waves/"'));
assert.ok(ocean.includes('"contentUrl":"https://media.whitenoisechoir.com/audio/ocean-waves-real.mp3"'));
assert.ok(!ocean.includes("whitenoisechoir.github.io"));
const urls=[...read("audits/sitemap-before-studio.xml").matchAll(/<loc>([^<]+)<\/loc>/g)].map(x=>x[1]);
assert.equal(urls.length,18);
assert.equal(new Set(urls).size,18);
assert.ok(urls.every(x=>x.startsWith("https://whitenoisechoir.com/")));
assert.ok(!urls.some(x=>x.includes("/framework-preview/")||x.includes("/sounds/bird-sounds/")));
const q=data("catalog/sound-production-queue-c6.json");
assert.equal(q.items.length,10);
assert.equal(q.summary.real_audio_acquired,0);
assert.equal(q.summary.master_mp3_produced,0);
assert.equal(q.summary.owner_listening_approved,0);
assert.ok(q.items.every(x=>x.source_audit.status==="UNSOURCED"&&x.review_audio===null&&x.seo.allow_index===false));
assert.ok(q.items.slice(0,2).every(x=>x.metadata_discovery?.[0]?.original_download_access==="FREESOUND_LOGIN_REQUIRED"));
assert.equal(q.items.find(x=>x.record_id==="SND-0040").alternative_leads[0].disposition,"BACKUP_RESEARCH_ONLY_NOT_SELECTED");
const l=data("catalog/library.json"),ledger=data("catalog/sound-release-approvals.json");
assert.equal(l.sounds.length,35);assert.deepEqual(ledger.approvals,[]);
const probe=cp.spawnSync(process.execPath,["--check","scripts/c6b_source_probe.cjs"],{encoding:"utf8"});
assert.equal(probe.status,0,probe.stderr);
console.log("C6B_PREFLIGHT_PASS reviewed Ocean/sitemap blobs, exact 18 .com index URLs, player preserved, 35 production assets and 10 unsourced candidates still gated");
