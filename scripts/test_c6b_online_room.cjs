#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict"),cp=require("node:child_process");
const load=p=>fs.readFileSync(p,"utf8");
const html=load("signature/c6b-online-review/index.html");
const upl=load("scripts/c6b_publish_review_r2.py");
const w=load(".github/workflows/c6b_online_audition.yml");
const sitemap=load("audits/sitemap-before-studio.xml");
const lib=JSON.parse(load("catalog/library.json"));
const ledger=JSON.parse(load("catalog/sound-release-approvals.json"));
const q=JSON.parse(load("catalog/sound-production-queue-c6.json"));
assert.ok(html.includes('name="robots" content="noindex,nofollow,noarchive"'));
assert.ok(!html.includes('rel="canonical"'));
assert.ok(!html.includes('application/ld+json'));
assert.ok(!sitemap.includes("/signature/c6b-online-review/"));
assert.ok(html.includes('id="seek"')&&html.includes('id="near-end"'));
assert.ok(html.includes('<audio id="player" controls loop preload="metadata"'),"Native audio loop must be enabled");
assert.ok(html.includes('<input type="checkbox" id="loop" checked>'),"Default loop checkbox must start checked");
assert.ok(html.includes('audio.loop=$("loop").checked;'),"Native loop must follow owner preference");
assert.ok(html.includes('audio.addEventListener("ended"'),"End-of-audio fallback should exist");
assert.ok(html.includes("audio.currentTime=audio.duration-5"));
assert.ok(html.includes("media.whitenoisechoir.com/review/c6b-20261110/"));
assert.ok(html.includes("noindex")&&html.includes("Freesound HQ preview"));
assert.equal((html.match(/<option value="SND-00(?:39|40)-(?:raw|balanced)"/g)||[]).length,4);
assert.ok(!html.includes("/audio/continuous/"),"Audition UI may not touch production HLS");
const js=html.split("<script>")[1]?.split("</script>")[0];assert.ok(js);
new vm.Script(js,{filename:"C6B online listening room"});
assert.equal(lib.sounds.length,35);
assert.deepEqual(ledger.approvals,[]);
assert.equal(q.items.length,10);
assert.equal(q.summary.master_mp3_produced,0);
assert.ok(q.items.every(x=>x.owner_listening.status==="NOT_REQUESTED"&&x.release_status==="BLOCKED"));
assert.ok(upl.includes('PREFIX="review/c6b-20261110/"'));
assert.ok(upl.includes('"SND-0039":"4585825b1f4b8c65c3023fe34d29df2b24e8d272fc0978733fbff32ff6300519"'));
assert.ok(upl.includes('"SND-0040":"4f1e1129bc044fe771947d478d0a30be7fcba968df590ee0dfe380d080086269"'));
assert.ok(upl.includes("client.put_object") && upl.includes("client.get_object"));
assert.ok(upl.includes("sha256") && upl.includes("public_range"));
assert.ok(!upl.includes("delete_object") && !upl.includes("copy_object"));
assert.ok(w.includes("push:")&&w.includes("branches: [main]"));
assert.ok(w.includes("actions/download-artifact@v4"));
assert.ok(w.includes("run-id: 42763529255"));
assert.ok(w.includes("if: github.event_name == 'push' && github.ref == 'refs/heads/main'"));
const secretStart="$"+"{{";
assert.ok(w.includes("R2_ACCESS_KEY_ID: "+secretStart+" secrets.R2_ACCESS_KEY_ID }}"));
assert.ok(w.includes("R2_SECRET_ACCESS_KEY: "+secretStart+" secrets.R2_SECRET_ACCESS_KEY }}"));
const release=JSON.parse(cp.execFileSync(process.execPath,["scripts/sound_release_gate.cjs","--id=SND-0039"],{encoding:"utf8"}));
assert.equal(release.ready,false);
console.log("C6B_ONLINE_REVIEW_STATIC_PASS: 4 isolated noindex audition variants; original 35 production, 45 presets and 18 sitemap URLs unaffected; source/owner release gate remains closed");
