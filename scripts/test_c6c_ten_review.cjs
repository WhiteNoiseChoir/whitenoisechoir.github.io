#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict"),cp=require("node:child_process");
const read=p=>fs.readFileSync(p,"utf8");
const manifest=JSON.parse(read("catalog/c6c-ten-synthetic-review.json"));
const registry=JSON.parse(read("catalog/sound-production-registry-c5.json"));
const lib=JSON.parse(read("catalog/library.json"));
const ledger=JSON.parse(read("catalog/sound-release-approvals.json"));
const html=read("signature/c6c-online-review/index.html");
const sitemap=read("sitemap.xml");
const renderer=read("scripts/c6c_render_ten_original_synth.py");
const uploader=read("scripts/c6c_publish_ten_review_r2.py");
assert.equal(manifest.items.length,10);
assert.equal(new Set(manifest.items.map(x=>x.id)).size,10);
assert.equal(registry.records.length,532);
assert.equal(lib.sounds.length,35);
assert.deepEqual(ledger.approvals,[]);
assert.equal(manifest.production_released,false);
assert.equal(manifest.owner_approval,false);
assert.equal(manifest.audio_spec.seconds,600);
assert.equal(manifest.audio_spec.mp3_sample_rate_hz,44100);
assert.equal(manifest.audio_spec.channels,2);
assert.equal(manifest.audio_spec.mp3_bitrate_kbps,192);
assert.equal(manifest.source_kind,"original_DSP_procedural_synthesis_not_field_recording");
const byId=new Map(registry.records.map(x=>[x.id,x]));
const released=new Set(lib.sounds.map(x=>x.id));
for(const x of manifest.items){
 const c=byId.get(x.id);
 assert.ok(c,"Unknown registry ID "+x.id);
 assert.equal(c.title_en,x.title);
 assert.equal(c.editorial_class,"SOURCE_CANDIDATE");
 assert.equal(c.existing_production,null);
 assert.equal(c.priority,x.priority);
 assert.equal(c.family_id,x.family);
 assert.ok(!released.has(x.id));
 assert.ok(!["SND-0039","SND-0040"].includes(x.id));
 assert.ok(x.review_label.includes("Synthetic"),"Synth must always be disclosed");
 assert.ok(x.qualifier);
 assert.ok(html.includes('<option value="'+x.id+'">'),"review track missing "+x.id);
}
assert.ok(html.includes('<meta name="robots" content="noindex,nofollow,noarchive">'));
assert.ok(!html.includes('rel="canonical"'));
assert.ok(!html.includes('application/ld+json'));
assert.ok(!sitemap.includes("/signature/c6c-online-review/"));
assert.ok(!sitemap.includes("c6c-20261110"));
assert.ok(html.includes('<audio id="audio" controls loop preload="metadata"'));
assert.ok(html.includes('<input id="loop" type="checkbox" checked>'));
assert.ok(html.includes('audio.loop=el("loop").checked'));
assert.ok(html.includes('audio.addEventListener("ended"'));
assert.ok(html.includes('id="seek"')&&html.includes('id="last"'));
const js=html.split("<script>")[1]?.split("</script>")[0];assert.ok(js);
new vm.Script(js,{filename:"C6C ten-synth reviewer"});
assert.ok(renderer.includes('FRAMES=SR*SECONDS')&&renderer.includes('self.rng'));
assert.ok(renderer.includes('self.state')&&renderer.includes('600'));
assert.ok(!renderer.includes('"stream_loop"')&&!renderer.includes('"aloop"'));
assert.ok(renderer.includes("full_mp3_decode"));
assert.ok(uploader.includes('PREFIX="review/c6c-20261110/"'));
assert.ok(uploader.includes('put_immutable'));
assert.ok(uploader.includes("sha256"));
assert.ok(uploader.includes("s3.get_object"));
assert.ok(!uploader.includes("delete_object")&&!uploader.includes("copy_object"));
const release=JSON.parse(cp.execFileSync(process.execPath,["scripts/sound_release_gate.cjs","--id=SND-0046"],{encoding:"utf8"}));
assert.equal(release.ready,false);
console.log("C6C_TEN_SOUND_REVIEW_STATIC_PASS: ten unique synthetically labeled candidates, original independent render contract, native loop, noindex, unchanged 35 production and 45 presets");
